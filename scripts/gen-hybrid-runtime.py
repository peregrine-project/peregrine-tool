#!/usr/bin/env python3
"""Regenerate theories/backends/HybridRuntimeGen.v from theories/backends/HybridRuntime.v.

Compiles scripts/HybridRuntimeExtract.v (which prints the runtime with the typed
Rust printer), keeps the printed methods of the runtime and its primitives, and
writes them as a Rocq list of strings.  Run from the repository root after the
theories are built:  python3 scripts/gen-hybrid-runtime.py [--installed]
"""
import resource
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "theories" / "backends" / "HybridRuntimeGen.v"

resource.setrlimit(resource.RLIMIT_STACK, (resource.RLIM_INFINITY, resource.RLIM_INFINITY))
# --installed: use the installed Peregrine library (CI, after opam install)
# instead of the theories compiled in this checkout.
qpath = [] if "--installed" in sys.argv else ["-Q", "theories", "Peregrine"]
res = subprocess.run(["rocq", "compile", *qpath, "scripts/HybridRuntimeExtract.v"],
                     cwd=ROOT, capture_output=True, text=True)
out = res.stdout
if res.returncode != 0 or '"' not in out:
    sys.exit(f"gen-hybrid-runtime: extraction failed:\n{res.stdout}\n{res.stderr}")
text = out[out.index('"') + 1: out.rindex('"')].replace('""', '"')

blocks, cur = [], None
for line in text.split("\n"):
    if line.startswith("fn "):
        if cur:
            blocks.append(cur)
        cur = [line]
    elif cur is not None:
        cur.append(line)
        if line == "}":
            blocks.append(cur)
            cur = None
methods = [b for b in blocks if b[0].startswith("fn Peregrine_backends_Hybrid")]
if not methods:
    sys.exit("gen-hybrid-runtime: no runtime method in the printed program")

lines = [l for b in methods for l in b]
body = ";\n".join('  "' + l.replace('"', '""') + '"' for l in lines)
OUT.write_text(
    "(** Generated by scripts/gen-hybrid-runtime.py from HybridRuntime.v; do not edit.\n"
    "    The methods of the [rust-hybrid] number runtime and of its primitives, as the\n"
    "    typed Rust printer prints them; [RustHybridRemaps.v] puts them in the program. *)\n\n"
    "From MetaRocq.Utils Require Import bytestring.\n"
    "From Stdlib Require Import List.\n"
    "Import ListNotations.\n"
    "Local Open Scope bs_scope.\n\n"
    "Definition hybrid_runtime_lines : list string := [\n" + body + "\n].\n")
print(f"gen-hybrid-runtime: {len(methods)} methods, {len(lines)} lines -> {OUT.relative_to(ROOT)}")
